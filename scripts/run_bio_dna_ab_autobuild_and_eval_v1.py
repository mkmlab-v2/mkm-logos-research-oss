"""Autobuild combined A/B CSV from existing artifacts and run holdout evaluation.

Default source mode:
- docs/final/artifacts/ab_result_timeseries.csv

Optional expanded source mode:
- reports/constitution/btrack_pilot/blind_replay/answer_key + multiple prediction profiles

Autobuild rules:
- Use rows where sample_id starts with BR_
- y_true      <- truth
- y_pred_treatment <- prediction
- y_pred_baseline  <- generated by baseline mode
"""

from __future__ import annotations

import argparse
import csv
import json
import random
import subprocess
import sys
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


def _utc_now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _pick_baseline(mode: str, truth: str, majority_label: str, labels: list[str], rng: random.Random) -> str:
    if mode == "neutral":
        return "NEUTRAL"
    if mode == "majority":
        return majority_label
    if mode == "oracle_shifted":
        # Deterministic non-trivial baseline: rotate among labels so it is not identical to treatment.
        if truth not in labels:
            return majority_label
        i = labels.index(truth)
        return labels[(i + 1) % len(labels)]
    if mode == "random":
        return rng.choice(labels)
    return "NEUTRAL"


def main() -> int:
    ap = argparse.ArgumentParser(description="Autobuild combined A/B CSV and run holdout evaluation.")
    root = Path(__file__).resolve().parents[1]
    ap.add_argument(
        "--source-csv",
        type=Path,
        default=root / "docs" / "final" / "artifacts" / "ab_result_timeseries.csv",
    )
    ap.add_argument(
        "--combined-out-csv",
        type=Path,
        default=root / "reports" / "bio_dna_ab_combined_autobuild_v1.csv",
    )
    ap.add_argument(
        "--eval-out-json",
        type=Path,
        default=root / "reports" / "bio_dna_ab_holdout_eval_v1_autobuild_latest.json",
    )
    ap.add_argument(
        "--build-report-json",
        type=Path,
        default=root / "reports" / "bio_dna_ab_autobuild_report_v1_latest.json",
    )
    ap.add_argument(
        "--baseline-mode",
        choices=["neutral", "majority", "oracle_shifted", "random"],
        default="majority",
    )
    ap.add_argument("--seed", type=int, default=20260421)
    ap.add_argument("--holdout-ratio", type=float, default=0.3)
    ap.add_argument("--bootstrap-iterations", type=int, default=2000)
    ap.add_argument("--min-holdout-samples", type=int, default=12)
    ap.add_argument("--min-abs-uplift", type=float, default=0.02)
    ap.add_argument(
        "--use-blind-replay-profiles",
        action="store_true",
        help="Build combined set from blind replay answer key + multiple prediction profile files.",
    )
    ap.add_argument(
        "--answer-key-jsonl",
        type=Path,
        default=root
        / "reports"
        / "constitution"
        / "btrack_pilot"
        / "blind_replay"
        / "blind_replay_answer_key_historical_btcusdt_1d_cfg6_w60_h10_s2_seed45.jsonl",
    )
    ap.add_argument(
        "--prediction-jsonl",
        action="append",
        default=[],
        help="Prediction jsonl path(s); if omitted in blind-replay mode, defaults to A/B/C/D/DS latest.",
    )
    ns = ap.parse_args()

    rows_in: list[dict[str, str]] = []
    mode = "timeseries_csv"
    source_desc: dict[str, Any] = {}
    if ns.use_blind_replay_profiles:
        mode = "blind_replay_profiles"
        if not ns.answer_key_jsonl.is_file():
            raise FileNotFoundError(f"missing answer-key-jsonl: {ns.answer_key_jsonl}")
        answer_map: dict[str, str] = {}
        for ln in ns.answer_key_jsonl.read_text(encoding="utf-8").splitlines():
            if not ln.strip():
                continue
            obj = json.loads(ln)
            sid = str(obj.get("sample_id") or "").strip()
            lab = str(obj.get("answer_label") or "").strip()
            if sid and lab:
                answer_map[sid] = lab

        pred_files = [Path(p) for p in ns.prediction_jsonl]
        if not pred_files:
            blind_root = (
                root
                / "reports"
                / "constitution"
                / "btrack_pilot"
                / "blind_replay"
            )
            pred_files = [
                blind_root / "blind_replay_predictions_12ai_proxy_A_latest.jsonl",
                blind_root / "blind_replay_predictions_12ai_proxy_B_latest.jsonl",
                blind_root / "blind_replay_predictions_12ai_proxy_C_latest.jsonl",
                blind_root / "blind_replay_predictions_12ai_proxy_D_latest.jsonl",
                blind_root / "blind_replay_predictions_12ai_proxy_DS_latest.jsonl",
            ]
        pred_files = [p for p in pred_files if p.is_file()]
        if not pred_files:
            raise RuntimeError("no valid prediction jsonl files found")

        for pf in pred_files:
            for ln in pf.read_text(encoding="utf-8").splitlines():
                if not ln.strip():
                    continue
                obj = json.loads(ln)
                sid = str(obj.get("sample_id") or "").strip()
                pred = str(obj.get("direction_sign") or "").strip()
                profile = str(obj.get("profile") or pf.stem).strip()
                truth = answer_map.get(sid)
                if not sid or not pred or not truth:
                    continue
                # Expand effective sample count by treating profile as distinct run sample.
                sid_ext = f"{sid}::{profile}"
                rows_in.append({"sample_id": sid_ext, "truth": truth, "prediction": pred})
        source_desc = {
            "answer_key_jsonl": str(ns.answer_key_jsonl.resolve()),
            "prediction_jsonl_files": [str(p.resolve()) for p in pred_files],
        }
    else:
        if not ns.source_csv.is_file():
            raise FileNotFoundError(f"missing source-csv: {ns.source_csv}")
        with ns.source_csv.open("r", encoding="utf-8", newline="") as f:
            reader = csv.DictReader(f)
            for row in reader:
                sid = str(row.get("sample_id") or "").strip()
                truth = str(row.get("truth") or "").strip()
                pred = str(row.get("prediction") or "").strip()
                if not sid.startswith("BR_"):
                    continue
                if not truth or not pred:
                    continue
                rows_in.append({"sample_id": sid, "truth": truth, "prediction": pred})
        source_desc = {"source_csv": str(ns.source_csv.resolve())}

    labels = sorted({r["truth"] for r in rows_in})
    if not labels:
        raise RuntimeError("no usable BR_ rows in source-csv")
    majority_label = Counter(r["truth"] for r in rows_in).most_common(1)[0][0]
    rng = random.Random(ns.seed)

    rows_out: list[dict[str, str]] = []
    for r in rows_in:
        rows_out.append(
            {
                "sample_id": r["sample_id"],
                "y_true": r["truth"],
                "y_pred_baseline": _pick_baseline(
                    ns.baseline_mode, r["truth"], majority_label, labels, rng
                ),
                "y_pred_treatment": r["prediction"],
            }
        )

    ns.combined_out_csv.parent.mkdir(parents=True, exist_ok=True)
    with ns.combined_out_csv.open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(
            f, fieldnames=["sample_id", "y_true", "y_pred_baseline", "y_pred_treatment"]
        )
        w.writeheader()
        w.writerows(rows_out)

    eval_script = root / "scripts" / "run_bio_dna_ab_holdout_eval_v1.py"
    cmd = [
        sys.executable,
        str(eval_script),
        "--combined-csv",
        str(ns.combined_out_csv),
        "--output-json",
        str(ns.eval_out_json),
        "--holdout-ratio",
        str(ns.holdout_ratio),
        "--bootstrap-iterations",
        str(ns.bootstrap_iterations),
        "--min-holdout-samples",
        str(ns.min_holdout_samples),
        "--min-abs-uplift",
        str(ns.min_abs_uplift),
        "--seed",
        str(ns.seed),
    ]
    proc = subprocess.run(cmd, check=False)
    if proc.returncode != 0:
        raise RuntimeError(f"holdout_eval_failed exit={proc.returncode}")

    report: dict[str, Any] = {
        "schema": "bio_dna_ab_autobuild_report_v1",
        "generated_at_utc": _utc_now(),
        "inputs": {
            "source_mode": mode,
            **source_desc,
            "baseline_mode": ns.baseline_mode,
            "seed": ns.seed,
        },
        "summary": {
            "rows_selected_from_source": len(rows_in),
            "rows_written_combined": len(rows_out),
            "label_set": labels,
            "majority_label": majority_label,
        },
        "outputs": {
            "combined_csv": str(ns.combined_out_csv.resolve()),
            "eval_json": str(ns.eval_out_json.resolve()),
        },
        "note": "Autobuild uses pre-existing artifact rows and synthetic baseline policy. Research-only.",
    }
    ns.build_report_json.parent.mkdir(parents=True, exist_ok=True)
    ns.build_report_json.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"WROTE: {ns.combined_out_csv.resolve()} rows={len(rows_out)}")
    print(f"WROTE: {ns.eval_out_json.resolve()}")
    print(f"WROTE: {ns.build_report_json.resolve()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

